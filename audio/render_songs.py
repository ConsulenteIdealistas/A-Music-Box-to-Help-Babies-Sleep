"""Music-box audition renders of the repertoire.

The scores live in audio/scores/*.musicxml (the single source of
truth, generated by audio/make_musicxml.py from the transcription
record). This module loads them and renders with a Python additive
model of a music-box tine (inharmonic partials 1 : 6.27 : 17.5 :
34.4, higher partials decaying faster) -- an AUDITION engine; the
final engine decision (SuperCollider/Klank vs recorded) is separate.

A soft root+fifth bass is derived from each measure's <harmony>.

Usage: python -m audio.render_songs --out-dir <dir>
"""

from __future__ import annotations

import argparse
import math
import struct
import wave
import xml.etree.ElementTree as ET
from pathlib import Path

SR = 44100
PARTIALS = [(1.0, 1.0, 2.8), (6.27, 0.32, 0.9), (17.5, 0.12, 0.35), (34.4, 0.05, 0.15)]
SCORES_DIR = Path(__file__).with_name("scores")

# seconds per quarter note, per score file (arranger's tempo choices)
TEMPO = {
    "brahms_wiegenlied": 60 / 63,
    "yurikago_no_uta": 1.0,
    "moldau_theme": 0.84,
    "vissi_darte": 0.75,
}
MELODY_GAIN = 0.5
BASS_ROOT_GAIN = 0.16
BASS_FIFTH_GAIN = 0.10

_STEP_SEMI = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}
_SHARP_NAMES = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"]


def name_to_midi(name: str) -> int:
    step, rest = name[0], name[1:]
    alter = 0
    if rest.startswith("b"):
        alter, rest = -1, rest[1:]
    elif rest.startswith("#"):
        alter, rest = 1, rest[1:]
    return 12 * (int(rest) + 1) + _STEP_SEMI[step] + alter


def midi_to_name(midi: int) -> str:
    return f"{_SHARP_NAMES[midi % 12]}{midi // 12 - 1}"


def freq(name: str) -> float:
    return 440.0 * 2 ** ((name_to_midi(name) - 69) / 12)


def load_score(path: Path):
    """Return (events, total_quarters): events are (start_q, name, gain)
    in quarter-note units, ties merged, bass derived from harmony."""
    root = ET.parse(path).getroot()
    part = root.find("part")
    divisions = 12
    events: list[tuple[float, str, float]] = []
    t_q = 0.0
    open_tie: dict | None = None
    for measure in part.findall("measure"):
        div_el = measure.find("attributes/divisions")
        if div_el is not None:
            divisions = int(div_el.text)
        time_el = measure.find("attributes/time")
        if time_el is not None:
            bar_q = int(time_el.findtext("beats")) * 4 / int(time_el.findtext("beat-type"))
        harmony = measure.find("harmony")
        if harmony is not None:
            rstep = harmony.findtext("root/root-step")
            ralter = int(harmony.findtext("root/root-alter") or 0)
            root_midi = 12 * 4 + _STEP_SEMI[rstep] + ralter  # octave 3
            events.append((t_q, midi_to_name(root_midi), BASS_ROOT_GAIN))
            events.append((t_q + bar_q / 2, midi_to_name(root_midi + 7), BASS_FIFTH_GAIN))
        for note in measure.findall("note"):
            dur_q = int(note.findtext("duration")) / divisions
            ties = [t.get("type") for t in note.findall("tie")]
            if note.find("rest") is not None:
                t_q += dur_q
                continue
            pitch = note.find("pitch")
            step = pitch.findtext("step")
            alter = int(pitch.findtext("alter") or 0)
            octave = int(pitch.findtext("octave"))
            name = midi_to_name(12 * (octave + 1) + _STEP_SEMI[step] + alter)
            if "stop" in ties and open_tie is not None:
                open_tie["dur"] += dur_q
            else:
                open_tie = {"start": t_q, "name": name, "dur": dur_q}
                events.append((t_q, name, MELODY_GAIN))
            if "start" not in ties:
                open_tie = None
            t_q += dur_q
    return events, t_q


def load_all() -> dict:
    songs = {}
    for path in sorted(SCORES_DIR.glob("*.musicxml")):
        key = path.stem
        events_q, total_q = load_score(path)
        beat_s = TEMPO[key]
        events = [(round(t * beat_s, 4), name, gain) for t, name, gain in events_q]
        songs[key] = {"events": events, "total_s": total_q * beat_s + 3.5}
    return songs


SONGS = load_all()


def add_note(buf: list[float], start_s: float, name: str, gain: float) -> None:
    f0 = freq(name)
    start = int(start_s * SR)
    dur = int(3.2 * SR)
    for ratio, amp, decay in PARTIALS:
        f = f0 * ratio
        if f > 16000:
            continue
        for i in range(dur):
            if start + i >= len(buf):
                return
            t = i / SR
            buf[start + i] += gain * amp * math.exp(-t / decay) * math.sin(2 * math.pi * f * t)


def write_wav(path: Path, samples: list[float]) -> None:
    peak = max(1e-9, max(abs(x) for x in samples))
    scale = min(1.0, 0.89 / peak)
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(b"".join(
            struct.pack("<h", int(max(-1.0, min(1.0, x * scale)) * 32767))
            for x in samples))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-dir", required=True)
    args = ap.parse_args()
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    for name, song in SONGS.items():
        buf = [0.0] * int(song["total_s"] * SR)
        for start, note, gain in song["events"]:
            add_note(buf, start, note, gain)
        write_wav(out / f"{name}_musicbox.wav", buf)
        print(f"{name}: {song['total_s']:.0f}s, {len(song['events'])} events")


if __name__ == "__main__":
    main()
